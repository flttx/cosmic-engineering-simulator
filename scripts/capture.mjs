import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';

const directory = '.impeccable/review';
await fs.mkdir(directory, { recursive: true });
await fs.mkdir('artifacts/demos', { recursive: true });
const browser = await chromium.launch({ headless: true, channel: 'chromium' });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1, recordVideo: { dir: 'artifacts/demos/raw', size: { width: 1440, height: 900 } } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:5174');
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(5000);
  await page.getByRole('button', { name: '暂停动画', exact: true }).click();
  await page.screenshot({ path: `${directory}/desktop.png` });
  await page.getByRole('button', { name: '巨构掠过', exact: false }).click();
  await page.waitForTimeout(6000);
  await page.screenshot({ path: `${directory}/flyby.png` });
  await page.mouse.move(650, 500);
  await page.mouse.down();
  await page.mouse.move(735, 510, { steps: 18 });
  await page.mouse.up();
  await page.getByRole('button', { name: '单体检查', exact: false }).click();
  await page.waitForTimeout(5000);
  await page.screenshot({ path: `${directory}/inspection.png` });
  await page.mouse.move(720, 440);
  await page.mouse.down();
  await page.mouse.move(960, 445, { steps: 24 });
  await page.mouse.up();
  await page.waitForTimeout(1000);
  await page.screenshot({ path: `${directory}/inspection-side.png` });
  await page.locator('.object-list').getByRole('button', { name: '承力桁架', exact: true }).click();
  await page.getByRole('button', { name: '隔离', exact: true }).click();
  await page.waitForTimeout(4000);
  await page.screenshot({ path: `${directory}/isolated.png` });
  await page.getByRole('button', { name: '画质与显示设置', exact: true }).click();
  await page.getByText('运行测量', { exact: true }).click();
  const measurements = await page.locator('.settings-panel').innerText();
  await page.getByRole('button', { name: '画质与显示设置', exact: true }).click();
  await page.getByRole('button', { name: '全景', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload();
  await page.waitForTimeout(5000);
  await page.screenshot({ path: `${directory}/mobile.png` });
  await page.setViewportSize({ width: 497, height: 639 });
  await page.reload();
  await page.locator('main[data-solar-status="ready"]').waitFor();
  await page.waitForTimeout(1500);
  await page.screenshot({ path: `${directory}/solar-mobile.png` });
  await page.mouse.move(245, 350);
  for (let index = 0; index < 18; index++) await page.mouse.wheel(0, -400);
  await page.waitForTimeout(1000);
  await page.screenshot({ path: `${directory}/solar-close.png` });
  await page.mouse.move(245, 350);
  await page.mouse.down();
  await page.mouse.move(380, 330, { steps: 20 });
  await page.mouse.up();
  await page.waitForTimeout(500);
  await page.screenshot({ path: `${directory}/solar-angle.png` });
  await fs.writeFile(`${directory}/capture.json`, JSON.stringify({ errors, measurements, capturedAt: new Date().toISOString() }, null, 2));
  process.stdout.write(JSON.stringify({ errors, measurements, directory }) + '\n');
  const video = page.video();
  await page.close();
  if (video) await video.saveAs('artifacts/demos/C01-observation.webm');
} finally { await browser.close(); }
